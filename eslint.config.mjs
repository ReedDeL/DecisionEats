/**
 * The style guide §2.5 gate: "A missing accessibilityLabel fails CI."
 *
 * The upstream plugin validates prop VALUES but has no rule requiring a label
 * at all, so this local rule covers the missing half. It inspects raw
 * react-native touchables only — shared interactive components (PrimaryButton,
 * Chip, ...) are covered by linting their own internals.
 */
const INTERACTIVE_COMPONENTS = new Set([
  'Pressable',
  'TouchableOpacity',
  'TouchableHighlight',
  'TouchableNativeFeedback',
  'TouchableWithoutFeedback',
]);

const interactiveNeedsLabel = {
  meta: {
    type: 'problem',
    docs: { description: 'Interactive elements need accessibilityLabel' },
    schema: [],
  },
  create(context) {
    return {
      JSXOpeningElement(node) {
        if (node.name?.type !== 'JSXIdentifier') return;
        if (!INTERACTIVE_COMPONENTS.has(node.name.name)) return;

        const hasLabel = node.attributes.some(
          (attribute) =>
            attribute.type === 'JSXAttribute' &&
            (attribute.name?.name === 'accessibilityLabel' || attribute.name?.name === 'aria-label')
        );
        if (hasLabel) return;

        context.report({
          node,
          message: `<${node.name.name}> is interactive: set accessibilityLabel, or use a shared component that sets one.`,
        });
      },
    };
  },
};

